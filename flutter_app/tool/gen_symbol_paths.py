#!/usr/bin/env python3
"""Round 11 — bakes the two religion symbols that are real letterforms (ॐ and the ☬ khanda)
into compact vector path strings (lib/widgets/religion_paths.dart), so the app draws them
as plain paths: no font glyph, no emoji font, same on every phone.

Outlines come from OFL fonts: ॐ from assets/fonts/NotoSansDevanagari-SemiBold.ttf, ☬ from
Noto Sans Symbols (fonts.google.com/noto). Needs `pip install fonttools`. Each outline is
scaled to fit a 0..1000 box (centred, y flipped) with integer coordinates.
Usage: python3 tool/gen_symbol_paths.py [path/to/NotoSansSymbols.ttf]
"""
import sys
from fontTools.ttLib import TTFont
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.recordingPen import RecordingPen

SYMBOLS_TTF = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/fonts/truetype/sand-box/google/Noto Sans Symbols/NotoSansSymbols-VariableFont_wght.ttf'
SOURCES = [
    ('om', 'assets/fonts/NotoSansDevanagari-SemiBold.ttf', 0x0950),
    ('khanda', SYMBOLS_TTF, 0x262C),
]


def outline(font_path, cp):
    f = TTFont(font_path)
    gs = f.getGlyphSet()
    name = f.getBestCmap()[cp]
    b = BoundsPen(gs)
    gs[name].draw(b)
    r = RecordingPen()
    gs[name].draw(r)
    return r.value, b.bounds


def path_data(ops, bounds):
    x0, y0, x1, y1 = bounds
    k = 1000 / max(x1 - x0, y1 - y0)
    ox = (1000 - (x1 - x0) * k) / 2
    oy = (1000 - (y1 - y0) * k) / 2

    def pt(p):
        return f'{round(ox + (p[0] - x0) * k)} {round(oy + (y1 - p[1]) * k)}'

    out = []
    for op, args in ops:
        if op == 'moveTo':
            out.append('M' + pt(args[0]))
        elif op == 'lineTo':
            out.append('L' + pt(args[0]))
        elif op == 'curveTo':
            out.append('C' + ' '.join(pt(a) for a in args))
        elif op == 'qCurveTo':
            # TrueType quadratic spline with implied on-curve points -> explicit quads
            pts = list(args)
            if pts[-1] is None:
                raise SystemExit('closed qCurve contour not supported')
            for i in range(len(pts) - 1):
                c = pts[i]
                if i < len(pts) - 2:
                    n = pts[i + 1]
                    e = ((c[0] + n[0]) / 2, (c[1] + n[1]) / 2)
                else:
                    e = pts[-1]
                out.append('Q' + pt(c) + ' ' + pt(e))
        elif op in ('closePath', 'endPath'):
            out.append('Z')
    return ''.join(out)


lines = [
    '// GENERATED by tool/gen_symbol_paths.py — do not edit. Outlines of ॐ and ☬ (OFL fonts), in a 0..1000 box.',
    '',
]
for name, fp, cp in SOURCES:
    ops, b = outline(fp, cp)
    d = path_data(ops, b)
    lines.append(f"const String kPath{name.capitalize()} = '{d}';")
    print(name, len(d), 'chars')
open('lib/widgets/religion_paths.dart', 'w').write('\n'.join(lines) + '\n')
