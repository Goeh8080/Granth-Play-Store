root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
S = json.load(open(os.path.join(root, 'assets/structure/structure.json'), encoding='utf-8'))
G = {x['id']: x for x in json.load(open(os.path.join(root, 'test/fixtures/granths_104.json'), encoding='utf-8'))}

