def leaves(r):
    for g in r['groups']:
        if 'subgroups' in g:
            for s in g['subgroups']:
                yield g, s
        else:
            yield g, None


def table(ids, notes=None):
    rows = ['| id | title | pramans | note |', '|---:|---|---:|---|']
    for i in sorted(ids, key=lambda i: (int(G[i]['position']), int(i))):
        n = (notes or {}).get(i, '') or INFER.get(i, '')
        t = G[i]['title'].replace('|', '/')
        rows.append(f"| {i} | {t} | {G[i]['pramanCount']} | {n} |")
    return '\n'.join(rows)


out = []
w = out.append
w('# Granth folders (religion → group → granth)\n')
w('<!-- generated by tool/gen_structure_doc.py — do not edit by hand -->\n')
