  'हिन्दू ॐ, इस्लाम ☪ (crescent + star), सिख खंडा ☬, ईसाई ✝, बुद्ध धर्मचक्र, जैन अहिंसा-हस्त with a wheel (round 12), कबीर चदरिया + दोहे का स्क्रॉल (round 12, replaces the इकतारा), अन्य (neutral four-square). '
